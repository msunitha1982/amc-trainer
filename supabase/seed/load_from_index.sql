-- Load (or refresh) public.problems straight from the published public/data/index.json, without
-- pasting the 180 KB problems.sql. Equivalent to supabase/seed/problems.sql. Set :ref to a commit SHA
-- or branch. Live ratings are kept on re-run.
--   psql "$SUPABASE_DB_URL" -v ref=main -f supabase/seed/load_from_index.sql
create extension if not exists http with schema extensions;

with src as (
  select (extensions.http_get(
    'https://raw.githubusercontent.com/msunitha1982/amc-trainer/' || :'ref' || '/public/data/index.json')).content::jsonb as d
), p as (
  select e as j from src, jsonb_array_elements(src.d -> 'problems') e
)
insert into public.problems (id, year, contests, topics, max_number, seed_rating, rating, rating_rd)
select j ->> 'id',
       (j ->> 'y')::int,
       array(select distinct case when t ->> 't' like '%-10%' then '10' else '12' end
               from jsonb_array_elements(j -> 'tests') t order by 1),
       array(select distinct split_part(tag, '.', 1) from jsonb_array_elements_text(j -> 'tp') tag order by 1),
       (select max((t ->> 'n')::int) from jsonb_array_elements(j -> 'tests') t),
       (j ->> 'r')::real, (j ->> 'r')::real, 150
  from p
on conflict (id) do update set year = excluded.year, contests = excluded.contests, topics = excluded.topics,
  max_number = excluded.max_number, seed_rating = excluded.seed_rating;

drop extension if exists http;

